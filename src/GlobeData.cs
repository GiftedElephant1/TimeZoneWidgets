        static byte[] _mask;
        static int _maskW, _maskH;

        public static int MaskWidth { get { EnsureMask(); return _maskW; } }
        public static int MaskHeight { get { EnsureMask(); return _maskH; } }

        /// <summary>Equirectangular land mask: 1 = land, 0 = water. Row 0 is the north pole, column 0 is 180°W.</summary>
        public static byte[] Mask { get { EnsureMask(); return _mask; } }

        static void EnsureMask()
        {
            if (_mask != null) return;
            int w = 1440, h = 720;
            using (var bmp = new Bitmap(w, h, PixelFormat.Format24bppRgb))
            {
                using (var g = Graphics.FromImage(bmp))
                {
                    g.Clear(Color.Black);
                    g.SmoothingMode = SmoothingMode.None;
                    foreach (var poly in Land)
                    {
                        // Draw each outline three times so shapes crossing the ±180° seam wrap cleanly.
                        for (int shift = -360; shift <= 360; shift += 360)
                        {
                            var pts = new PointF[poly.Length / 2];
                            for (int i = 0; i < pts.Length; i++)
                            {
                                float lon = (float)poly[2 * i] + shift;
                                float lat = (float)poly[2 * i + 1];
                                pts[i] = new PointF((lon + 180f) / 360f * w, (90f - lat) / 180f * h);
                            }
                            g.FillPolygon(Brushes.White, pts);
                        }
                    }
                }
                var data = bmp.LockBits(new Rectangle(0, 0, w, h), ImageLockMode.ReadOnly, PixelFormat.Format24bppRgb);
                try
                {
                    var row = new byte[data.Stride];
                    var mask = new byte[w * h];
                    for (int y = 0; y < h; y++)
                    {
                        System.Runtime.InteropServices.Marshal.Copy(new IntPtr(data.Scan0.ToInt64() + y * data.Stride), row, 0, data.Stride);
                        for (int x = 0; x < w; x++) mask[y * w + x] = row[x * 3] > 127 ? (byte)1 : (byte)0;
                    }
                    _mask = mask;
                    _maskW = w;
                    _maskH = h;
                }
                finally
                {
                    bmp.UnlockBits(data);
                }
            }
        }
    }
